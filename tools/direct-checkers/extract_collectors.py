#!/usr/bin/env python3
"""Deterministically extract reviewed embedded Python; never run workflow shell/publish steps."""
import hashlib, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = {'github':'important-update-github-feed.yml','public':'important-update-public-feed.yml','tibo':'important-update-tibo-feed.yml','media':'important-update-reddit-media-feed.yml','recovery':'important-update-outage-recovery.yml'}

def extract():
    provenance = {}
    for key, filename in SOURCES.items():
        path = ROOT / 'vendor/.github/workflows' / filename
        text = path.read_text()
        blocks = re.findall(r"          python - <<'PY'\n(.*?)\n          PY", text, re.S)
        blocks = ['\n'.join(line[10:] if line.startswith('          ') else line for line in b.splitlines())+'\n' for b in blocks]
        selected = blocks[:2] if key == 'media' else blocks[:1]
        code = '\n'.join(selected)
        # Only execution/storage integration changes; acquisition/filtering schemas stay upstream.
        if key == 'github':
            a, b = code.index('previous_heads = {}'), code.index('index_repos = []')
            code = code[:a]+"previous_heads = {}\ntry:\n    old_doc = json.loads(pathlib.Path('previous/index.json').read_text())\n    previous_heads = {r['full_name']: r['head_sha'] for r in old_doc.get('repos', []) if r.get('full_name') and r.get('head_sha')}\nexcept (OSError, ValueError):\n    pass\n\n"+code[b:]
        elif key == 'media':
            a, b = code.index('previous = {}'), code.index('errors = []\nitems = []')
            code = code[:a]+"previous = {}\ntry:\n    previous = {item.get('id'): item for item in json.loads(pathlib.Path('previous/views/reddit_media.json').read_text()).get('items', [])}\nexcept (OSError, ValueError):\n    pass\n\n"+code[b:]
            code = code.replace('/tmp/media_candidates.json', 'media_candidates.json')
        elif key == 'recovery':
            a, b = code.index("state = {'schema_version'"), code.index('def window_for(key):')
            code = code[:a]+"state = {'schema_version': 1, 'sources': {}}\ntry:\n    state = json.loads(pathlib.Path('previous/state.json').read_text())\n    if not isinstance(state.get('sources'), dict):\n        raise ValueError('invalid recovery state')\nexcept (OSError, ValueError):\n    state = {'schema_version': 1, 'sources': {}}\n\n"+code[b:]
            code = code.replace('/tmp/important-update-recovery-state.json', 'hot/state.json')
            # Do not lose the missing portion of a partial recovery window.
            code = code.replace("if status == 'ok':\n        new_state", "if status == 'ok' and coverage_complete and not window['lookback_capped']:\n        new_state")
        if key == 'recovery':
            # Missing/malformed timestamps are not proof that a recovery window is empty.
            start=code.index("window = window_for('reddit')")
            end=code.index("window = window_for('tibo')")
            section=code[start:end].replace("if stamp:\n            fetched_times.append(stamp)","if stamp:\n            fetched_times.append(stamp)\n        else:\n            reddit_complete = False")
            code=code[:start]+section+code[end:]
            start=code.index("window = window_for('codex_resets')")
            section=code[start:].replace("if stamp:\n            fetched_times.append(stamp)","if stamp:\n            fetched_times.append(stamp)\n        else:\n            reset_complete = False")
            code=code[:start]+section
            code=code.replace("if fetched_times and min(fetched_times) > window['since']:","if not fetched_times or min(fetched_times) > window['since']:")
            code=code.replace("if stamps and min(stamps) > window['since']:","if not stamps or len(stamps) != len(fetched_all) or min(stamps) > window['since']:")
        code = "# Generated by extract_collectors.py; see provenance.json.\n"+code
        compile(code, filename, 'exec')
        (ROOT/'collectors'/f'{key}.py').write_text(code)
        provenance[key] = {'workflow':filename,'source_sha256':hashlib.sha256(text.encode()).hexdigest(),'collector_sha256':hashlib.sha256(code.encode()).hexdigest()}
    (ROOT/'provenance.json').write_text(json.dumps({'repository':'Happypig375/actions-experiment','commit':'e0b0bf9358bb0f694eb381fa6f027b7e651de523','collectors':provenance},indent=2)+'\n')
if __name__ == '__main__': extract()
